# -*- coding: utf-8 -*-
"""High-level client wrapper for the eLabFTW API v2.

This module exposes :class:`Client`, which wraps the Python API `elabapi_python` of eLabFTW, and
provides convenience helpers for experiments, uploads, categories, statuses,
and templates.

@author Thibaut Jacqmin
"""

import elabapi_python as ep
from functools import wraps
from inspect import signature
import json
from pathlib import Path
import re
from urllib.parse import urlsplit
import warnings
from urllib3.exceptions import InsecureRequestWarning
from .config import resolve_config_path
from .experiment import Experiment
from .resource import Resource
from .exceptions import (
    AmbiguousTitle,
    InvalidTemplate,
    InvalidTitle,
    InvalidID,
    DuplicateTitle,
    InvalidCategory,
    OwnershipTransferError,
)
from typing import Optional, Union


def _api_type(legacy_name: str, current_name: str):
    """Resolve API classes renamed by elabapi-python 6 without modifying it."""
    return getattr(ep, legacy_name, None) or getattr(ep, current_name)


class Client:
    """Convenience wrapper around the autogenerated eLabFTW API client.

    The client reads a simple key/value configuration file and initializes
    the API objects required to manage experiments and related entities.
    """

    def __init__(self, config_path: str | Path | None = None):
        """Initialize the client and underlying API objects.

        Args:
            config_path: Optional explicit configuration file. By default use
                the root project's ``[tool.elablink].config_path`` setting.
        """
        self.config_path = resolve_config_path(config_path)
        # Read and parse configuration file
        self.config = self._read_configuration_file(self.config_path)

        # API configuration
        self._api_configuration()

        # Load useful API objects
        self.experiments = ep.ExperimentsApi(self.api_client)
        self.items = ep.ItemsApi(self.api_client)
        self.uploads = ep.UploadsApi(self.api_client)
        self.steps = ep.StepsApi(self.api_client)
        self.comments = ep.CommentsApi(self.api_client)
        self.categories = _api_type(
            "ExperimentCategoriesApi", "ExperimentsCategoriesApi"
        )(self.api_client)
        self.resource_categories = _api_type(
            "ItemsTypesResourcesTemplatesApi", "ItemsTypesApi"
        )(self.api_client)
        self.statuses = _api_type(
            "ExperimentStatusApi", "ExperimentsStatusApi"
        )(self.api_client)
        self.resource_statuses = _api_type(
            "ResourceStatusApi", "ResourcesStatusApi"
        )(self.api_client)
        self.templates = ep.ExperimentsTemplatesApi(self.api_client)
        self.tags = ep.TagsApi(self.api_client)
        self.team_tags = ep.TeamTagsApi(self.api_client)
        self.item_links = ep.LinksToItemsApi(self.api_client)
        self.experiment_links = ep.LinksToExperimentsApi(self.api_client)
        self._team_id: int | None = None

    def download_upload(
        self,
        entity_type: str,
        entity_id: int,
        upload_id: int,
    ) -> bytes:
        """Download raw bytes of an upload from eLabFTW.

        Args:
            entity_type: Entity type string used by the API (e.g., "experiments").
            entity_id: Entity identifier.
            upload_id: Upload identifier.

        Returns:
            Raw bytes of the remote upload.
        """
        # Important: _preload_content=False to get a raw HTTP response object
        resp = self.uploads.read_upload(
            entity_type,
            entity_id,
            upload_id,
            format="binary",
            _preload_content=False,
        )

        complete = False
        try:
            read = getattr(resp, "read", None)
            if read is not None:
                result = read()
            elif hasattr(resp, "data"):
                result = resp.data
            else:
                result = bytes(resp)
            complete = True
            return result
        finally:
            try:
                close = getattr(resp, "close", None)
                if not complete and close is not None:
                    close()
            finally:
                release = getattr(resp, "release_conn", None)
                if release is not None:
                    release()

    def replace_upload(
        self,
        entity_type: str,
        entity_id: int,
        upload_id: int,
        file_path: str | Path,
        comment: str = "Uploaded via API",
    ) -> None:
        """Upload a new version and archive the previous attachment.

        The generated replacement method omits the multipart ``action`` field;
        eLabFTW then creates another active file instead of replacing the old one.
        """
        self.api_client.call_api(
            "/{entity_type}/{id}/uploads/{subid}",
            "POST",
            path_params={"entity_type": entity_type, "id": entity_id, "subid": upload_id},
            header_params={"Accept": "application/json", "Content-Type": "multipart/form-data"},
            post_params=[("action", "replace"), ("comment", comment)],
            files={"file": str(file_path)},
            auth_settings=["token"],
            response_type=None,
            _return_http_data_only=True,
        )

    def load_experiment(self, ID: int = None, title: str = None):
        """Load an experiment by ID or by title.

        Args:
            ID: Experiment numeric identifier.
            title: Experiment title to resolve to an ID.

        Returns:
            An :class:`Experiment` instance if the experiment exists.

        Raises:
            InvalidTitle: When title is provided but does not exist.
            AmbiguousTitle: When several experiments have the requested title.
            InvalidID: When ID is provided but does not exist.
        """
        if title is not None:
            self.experiments_list = self.experiments.read_experiments()
            ID = self._resolve_title(self.experiments_list, title, "experiment")
        if ID is not None:
            experiment = Experiment(self, ID=ID)
            try:
                experiment.refresh()
            except ep.rest.ApiException as exc:
                if exc.status == 404:
                    raise InvalidID(ID) from exc
                raise
            return experiment
        raise InvalidID(ID)

    def create_resource(self, title: str, category: str | int | None = None) -> Resource:
        """Create an eLabFTW resource/item.

        ``category`` accepts an accessible resource category name or numeric ID.
        """
        category_id = None
        if category is not None:
            category_id = Resource._resolve_existing_id(
                category, self.resource_category_dict, InvalidCategory
            )
        body = {}
        if category_id is not None:
            body["category_id"] = int(category_id)
        _, _, headers = self.items.post_item_with_http_info(body=body)
        resource_id = int(headers["Location"].rstrip("/").split("/")[-1])
        resource = Resource(self, resource_id)
        updates = {"title": title}
        if category_id is not None:
            updates["category"] = int(category_id)
        resource._sync(updates)
        return resource

    def load_resource(self, ID: int = None, title: str = None) -> Resource:
        """Load a resource/item by ID or an unambiguous exact title."""
        if title is not None:
            ID = self._resolve_title(self.items.read_items(), title, "resource")
        if ID is not None:
            resource = Resource(self, ID)
            try:
                resource.refresh()
            except ep.rest.ApiException as exc:
                if exc.status == 404:
                    raise InvalidID(ID) from exc
                raise
            return resource
        raise InvalidID(ID)

    def _resolve_category_id(self, category: Union[int, str]) -> int:
        """Resolve a category name or ID to a valid category ID."""
        return Experiment._resolve_existing_id(
            category, self.category_dict, InvalidCategory
        )

    def experiment_creation_wrapper(func):
        """Decorator to normalize experiment creation and return Experiment."""
        call_signature = signature(func)

        @wraps(func)
        def wrapper(self, *args, **kwargs):
            bound = call_signature.bind(self, *args, **kwargs)
            bound.apply_defaults()
            title = bound.arguments["title"]
            category = bound.arguments["category"]
            owner_id = bound.arguments["owner_id"]
            team_id = bound.arguments["team_id"]
            if owner_id is None and team_id is not None:
                raise ValueError("team_id requires owner_id")
            if owner_id is not None:
                Experiment._validate_ownership_id(owner_id, "owner_id")
                team_id = Experiment._validate_ownership_id(
                    self._get_team_id() if team_id is None else team_id, "team_id"
                )
            if self.enforce_unique_titles and self._has_title(title):
                raise DuplicateTitle(title)
            category_id: Optional[int] = None
            if category is not None:
                category_id = self._resolve_category_id(category)
            headers = func(*bound.args, **bound.kwargs)
            ID = int(headers["Location"].split("/")[-1])
            experiment = Experiment(self, ID)
            updates = {}
            # Template creation doesn't take title in POST body, so patch it once here.
            if "template_name" in bound.arguments:
                updates["title"] = title
            if category_id is not None:
                updates["category"] = category_id
            if updates:
                experiment._sync(updates)
            if owner_id is not None:
                try:
                    experiment.transfer_ownership(owner_id, team_id=team_id)
                except Exception as exc:
                    raise OwnershipTransferError(
                        experiment.entity_type, ID,
                        "The experiment was created, but ownership assignment "
                        "could not be completed or verified. Load this ID and "
                        "inspect its owner before retrying; do not create it again.",
                    ) from exc
            return experiment

        return wrapper

    @experiment_creation_wrapper
    def create_experiment(
        self, title: str, category: Union[int, str] = None,
        *, owner_id: int | None = None, team_id: int | None = None,
    ):
        """Create an experiment, optionally transferring ownership as the last step.

        owner_id must identify an existing user in the destination team, which
        defaults to the current team. Assignment requires server permission.
        If assignment fails, OwnershipTransferError contains the created ID.
        """
        _, _, headers = self.experiments.post_experiment_with_http_info(
            body={"title": title}
        )
        return headers

    @experiment_creation_wrapper
    def create_experiment_from_template(
        self, title: str, template_name: str, category: Union[int, str] = None,
        *, owner_id: int | None = None, team_id: int | None = None,
    ):
        """Create a new experiment from an existing template."""
        template_id = self._get_template_id(name=template_name)
        if template_id is None:
            raise InvalidTemplate(template_name)
        _, _, headers = self.experiments.post_experiment_with_http_info(
            body={"template": template_id}
        )
        return headers

    @staticmethod
    def _titles_dict(records, kind: str) -> dict[str, int]:
        titles = {}
        for record in records:
            titles.setdefault(record.title, set()).add(int(record.id))
        for title, ids in titles.items():
            if len(ids) > 1:
                raise AmbiguousTitle(title, ids, kind)
        return {title: next(iter(ids)) for title, ids in titles.items()}

    @classmethod
    def _resolve_title(cls, records, title: str, kind: str) -> int:
        matches = [record for record in records if record.title == title]
        if not matches:
            raise InvalidTitle(title)
        return cls._titles_dict(matches, kind)[title]

    @property
    def experiments_dict(self) -> dict[str, int]:
        """Return title-to-ID choices, raising AmbiguousTitle for duplicate titles."""
        self.experiments_list = self.experiments.read_experiments()
        return self._titles_dict(self.experiments_list, "experiment")

    @property
    def resources_dict(self) -> dict[str, int]:
        """Return title-to-ID choices, raising AmbiguousTitle for duplicate titles."""
        return self._titles_dict(self.items.read_items(), "resource")

    @property
    def tag_dict(self) -> dict[str, int]:
        """Return existing tag names and IDs from the selected team."""
        # The generated client declares a single tag, but this endpoint returns a list.
        response = self.team_tags.read_team_tags(
            self._get_team_id(), _preload_content=False
        )
        try:
            tags = json.loads(response.data)
        finally:
            response.release_conn()
        return {tag["tag"]: int(tag["id"]) for tag in tags}

    @property
    def category_dict(self) -> dict[str, int]:
        """Return a map of experiment category titles to IDs."""
        # Returns all possible categories in a dictionary {category_name: category_id}
        team_id = self._get_team_id()
        cats = self.categories.read_team_experiments_categories(team_id)
        return {cat.title: cat.id for cat in cats}

    @property
    def resource_category_dict(self) -> dict[str, int]:
        """Return resource categories, or an empty dictionary when none are available."""
        categories = self.resource_categories.read_items_types() or []
        return {category.title: category.id for category in categories}

    @property
    def status_dict(self) -> dict[str, int]:
        """Return a map of experiment status titles to IDs."""
        # Returns all possible statuses in a dictionary {status_name: status_id}
        team_id = self._get_team_id()
        return {
            s.title: s.id for s in self.statuses.read_team_experiments_status(team_id)
        }

    @property
    def resource_status_dict(self) -> dict[str, int]:
        """Return resource statuses, or an empty dictionary when none are available."""
        team_id = self._get_team_id()
        return {
            s.title: s.id
            for s in self.resource_statuses.read_team_items_status(team_id) or []
        }

    def _get_team_id(self) -> int:
        """Resolve and cache the team ID used for categories/statuses."""
        if self._team_id is not None:
            return self._team_id

        raw = self.config.get("TEAM_ID")
        if raw:
            try:
                self._team_id = int(raw)
                return self._team_id
            except ValueError as exc:
                raise ValueError(f"Invalid TEAM_ID value: {raw!r}") from exc

        try:
            team = ep.TeamsApi(self.api_client).read_team("current")
        except Exception as exc:
            raise RuntimeError(
                "TEAM_ID is not set and the team could not be resolved. "
                "Set TEAM_ID in elablink.conf."
            ) from exc

        team_id = None
        if isinstance(team, dict):
            team_id = team.get("id")
        else:
            team_id = getattr(team, "id", None)
        if team_id is None:
            raise RuntimeError(
                "Unable to determine team ID. Set TEAM_ID in elablink.conf."
            )
        self._team_id = int(team_id)
        return self._team_id

    def _get_template_id(self, name: str) -> Optional[int]:
        """Resolve an experiment template by name to its ID."""
        templates = self.templates.read_experiments_templates()
        for t in templates:
            if t.title == name:
                return t.id
        return None

    def _has_title(self, title: str) -> bool:
        """Check if an experiment title exists."""
        return any(experiment.title == title for experiment in self.experiments.read_experiments())

    def _api_configuration(self):
        """Apply API settings from configuration to the OpenAPI client."""
        # Configures the API
        self.configuration = ep.Configuration()
        self.configuration.host = self.config["API_HOST_URL"].strip()
        self.configuration.api_key["Authorization"] = self.config["API_KEY"]
        self.configuration.verify_ssl = self._boolean_setting("VERIFY_SSL", default="true")
        allow_http = self._boolean_setting("ALLOW_INSECURE_HTTP", default="false")
        host = urlsplit(self.configuration.host)
        if host.scheme not in {"https", "http"} or not host.hostname:
            raise ValueError("API_HOST_URL must be an absolute HTTPS URL.")
        if host.scheme == "http" and not allow_http:
            raise ValueError(
                "API_HOST_URL must use HTTPS. Plain HTTP sends the API key without encryption; "
                "set ALLOW_INSECURE_HTTP=true only for an intentionally insecure connection."
            )
        if not self.configuration.verify_ssl and host.scheme == "https" and host.hostname:
            # Keep the certificate warning visible once for this server.
            warnings.filterwarnings(
                "once",
                message=(
                    "^Unverified HTTPS request is being made to host '"
                    + re.escape(host.hostname)
                    + r"'\."
                ),
                category=InsecureRequestWarning,
                module=r"^urllib3\.connectionpool$",
            )
        self.api_client = ep.ApiClient(self.configuration)
        self.api_client.set_default_header(
            header_name="Authorization",
            header_value=self.configuration.api_key["Authorization"],
        )
        self.enforce_unique_titles = (
            self.config["UNIQUE_EXPERIMENTS_TITLES"].lower() == "true"
        )

    def _boolean_setting(self, name: str, *, default: str) -> bool:
        value = self.config.get(name, default)
        if not isinstance(value, str) or value.strip().lower() not in {"true", "false"}:
            raise ValueError(f"{name} must be true or false.")
        return value.strip().lower() == "true"

    @staticmethod
    def _read_configuration_file(config_path: str) -> dict[str, str]:
        """Read key/value configuration file into a dictionary."""
        # Reads and parse configuration file, returns dictionnary
        config = {}
        with open(config_path) as f:
            for line in f:
                if line.strip() and not line.startswith("#"):
                    key, value = line.strip().split("=", 1)
                    config[key] = value
        return config
