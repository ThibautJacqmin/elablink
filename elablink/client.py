# -*- coding: utf-8 -*-
"""High-level client wrapper for the eLabFTW API v2.

This module exposes :class:`Client`, which wraps the Python API `elabapi_python` of eLabFTW, and
provides convenience helpers for experiments, uploads, categories, statuses,
and templates.

@author Thibaut Jacqmin
"""

import elabapi_python as ep
from functools import wraps
from inspect import signature
from .experiment import Experiment
from .resource import Resource
from .exceptions import (
    InvalidTemplate,
    InvalidTitle,
    InvalidID,
    DuplicateTitle,
    InvalidCategory,
)
from typing import Optional, Union

class Client:
    """Convenience wrapper around the autogenerated eLabFTW API client.

    The client reads a simple key/value configuration file and initializes
    the API objects required to manage experiments and related entities.
    """

    def __init__(self, config_path: str = "elablink.conf"):
        """Initialize the client and underlying API objects.

        Args:
            config_path: Path to the `elablink.conf` configuration file.
        """
        self.config_path = config_path
        # Read and parse configuration file
        self.config = self._read_configuration_file(config_path)

        # API configuration
        self._api_configuration()

        # Load useful API objects
        self.experiments = ep.ExperimentsApi(self.api_client)
        self.items = ep.ItemsApi(self.api_client)
        self.uploads = ep.UploadsApi(self.api_client)
        self.steps = ep.StepsApi(self.api_client)
        self.comments = ep.CommentsApi(self.api_client)
        self.categories = ep.ExperimentsCategoriesApi(self.api_client)
        self.statuses = ep.ExperimentsStatusApi(self.api_client)
        self.resource_statuses = ep.ResourcesStatusApi(self.api_client)
        self.templates = ep.ExperimentsTemplatesApi(self.api_client)
        self.tags = ep.TagsApi(self.api_client)
        self.item_links = ep.LinksToItemsApi(self.api_client)
        self.experiment_links = ep.LinksToExperimentsApi(self.api_client)
        self._team_id: int | None = None

    def download_upload(
        self,
        entity_type: str,
        entity_id: int,
        upload_id: int,
    ) -> bytes:
        """Download raw bytes of an upload from eLabFTW.

        Args:
            entity_type: Entity type string used by the API (e.g., "experiments").
            entity_id: Entity identifier.
            upload_id: Upload identifier.

        Returns:
            Raw bytes of the remote upload.
        """
        # Important: _preload_content=False to get a raw HTTP response object
        resp = self.uploads.read_upload(
            entity_type,
            entity_id,
            upload_id,
            format="binary",
            _preload_content=False,
        )

        # Depending on swagger/openapi generator, resp can be:
        # - urllib3.HTTPResponse (has .data)
        # - a file-like object (has .read())
        if hasattr(resp, "data"):
            return resp.data  # type: ignore[attr-defined]
        if hasattr(resp, "read"):
            return resp.read()  # type: ignore[no-any-return]
        # fallback: try bytes() (rare)
        return bytes(resp)

    def load_experiment(self, ID: int = None, title: str = None):
        """Load an experiment by ID or by title.

        Args:
            ID: Experiment numeric identifier.
            title: Experiment title to resolve to an ID.

        Returns:
            An :class:`Experiment` instance if the experiment exists.

        Raises:
            InvalidTitle: When title is provided but does not exist.
            InvalidID: When ID is provided but does not exist.
        """
        if title is not None:
            experiments_map = self.experiments_dict
            resolved = experiments_map.get(title)
            if resolved is None:
                raise InvalidTitle(title)
            ID = resolved
        if ID is not None:
            experiment = Experiment(self, ID=ID)
            try:
                experiment.refresh()
            except ep.rest.ApiException as exc:
                if exc.status == 404:
                    raise InvalidID(ID) from exc
                raise
            return experiment
        raise InvalidID(ID)

    def create_resource(self, title: str, category: int | None = None) -> Resource:
        """Create an eLabFTW resource/item.

        Resource categories are installation-specific, so ``category`` is a
        numeric eLabFTW category ID.
        """
        body = {}
        if category is not None:
            body["category_id"] = int(category)
        _, _, headers = self.items.post_item_with_http_info(body=body)
        resource_id = int(headers["Location"].rstrip("/").split("/")[-1])
        resource = Resource(self, resource_id)
        updates = {"title": title}
        if category is not None:
            updates["category"] = int(category)
        resource._sync(updates)
        return resource

    def load_resource(self, ID: int = None, title: str = None) -> Resource:
        """Load a resource/item by ID or exact title."""
        if title is not None:
            resources = self.resources_dict
            resolved = resources.get(title)
            if resolved is None:
                raise InvalidTitle(title)
            ID = resolved
        if ID is not None:
            resource = Resource(self, ID)
            try:
                resource.refresh()
            except ep.rest.ApiException as exc:
                if exc.status == 404:
                    raise InvalidID(ID) from exc
                raise
            return resource
        raise InvalidID(ID)

    def _resolve_category_id(self, category: Union[int, str]) -> int:
        """Resolve a category name or ID to a valid category ID."""
        categories = self.category_dict
        if isinstance(category, int):
            if category in categories.values():
                return category
            raise InvalidCategory(str(category))
        resolved = categories.get(category)
        if resolved is None:
            raise InvalidCategory(category)
        return int(resolved)

    def experiment_creation_wrapper(func):
        """Decorator to normalize experiment creation and return Experiment."""
        call_signature = signature(func)

        @wraps(func)
        def wrapper(self, *args, **kwargs):
            bound = call_signature.bind(self, *args, **kwargs)
            bound.apply_defaults()
            title = bound.arguments["title"]
            category = bound.arguments["category"]
            if self.enforce_unique_titles and self._has_title(title):
                raise DuplicateTitle(title)
            category_id: Optional[int] = None
            if category is not None:
                category_id = self._resolve_category_id(category)
            headers = func(*bound.args, **bound.kwargs)
            ID = int(headers["Location"].split("/")[-1])
            experiment = Experiment(self, ID)
            updates = {}
            # Template creation doesn't take title in POST body, so patch it once here.
            if "template_name" in bound.arguments:
                updates["title"] = title
            if category_id is not None:
                updates["category"] = category_id
            if updates:
                experiment._sync(updates)
            return experiment

        return wrapper

    @experiment_creation_wrapper
    def create_experiment(self, title: str, category: Union[int, str] = None):
        """Create a new experiment and return an :class:`Experiment`."""
        _, _, headers = self.experiments.post_experiment_with_http_info(
            body={"title": title}
        )
        return headers

    @experiment_creation_wrapper
    def create_experiment_from_template(
        self, title: str, template_name: str, category: Union[int, str] = None
    ):
        """Create a new experiment from an existing template."""
        template_id = self._get_template_id(name=template_name)
        if template_id is None:
            raise InvalidTemplate(template_name)
        _, _, headers = self.experiments.post_experiment_with_http_info(
            body={"template": template_id}
        )
        return headers

    @property
    def experiments_dict(self) -> dict[str, int]:
        """Return a map of experiment titles to IDs."""
        # This method returns a dictionnary containing titles as keys
        # and ids as values {title: id}
        self.experiments_list = self.experiments.read_experiments()
        return {exp.title: exp.id for exp in self.experiments_list}

    @property
    def resources_dict(self) -> dict[str, int]:
        """Return a map of accessible resource titles to IDs."""
        return {item.title: item.id for item in self.items.read_items()}

    @property
    def category_dict(self) -> dict[str, int]:
        """Return a map of experiment category titles to IDs."""
        # Returns all possible categories in a dictionary {category_name: category_id}
        team_id = self._get_team_id()
        cats = self.categories.read_team_experiments_categories(team_id)
        return {cat.title: cat.id for cat in cats}

    @property
    def status_dict(self) -> dict[str, int]:
        """Return a map of experiment status titles to IDs."""
        # Returns all possible statuses in a dictionary {status_name: status_id}
        team_id = self._get_team_id()
        return {
            s.title: s.id for s in self.statuses.read_team_experiments_status(team_id)
        }

    @property
    def resource_status_dict(self) -> dict[str, int]:
        """Return a map of resource status titles to IDs."""
        team_id = self._get_team_id()
        return {
            s.title: s.id
            for s in self.resource_statuses.read_team_items_status(team_id)
        }

    def _get_team_id(self) -> int:
        """Resolve and cache the team ID used for categories/statuses."""
        if self._team_id is not None:
            return self._team_id

        raw = self.config.get("TEAM_ID")
        if raw:
            try:
                self._team_id = int(raw)
                return self._team_id
            except ValueError as exc:
                raise ValueError(f"Invalid TEAM_ID value: {raw!r}") from exc

        try:
            team = ep.TeamsApi(self.api_client).read_team("current")
        except Exception as exc:
            raise RuntimeError(
                "TEAM_ID is not set and the team could not be resolved. "
                "Set TEAM_ID in elablink.conf."
            ) from exc

        team_id = None
        if isinstance(team, dict):
            team_id = team.get("id")
        else:
            team_id = getattr(team, "id", None)
        if team_id is None:
            raise RuntimeError(
                "Unable to determine team ID. Set TEAM_ID in elablink.conf."
            )
        self._team_id = int(team_id)
        return self._team_id

    def _get_template_id(self, name: str) -> Optional[int]:
        """Resolve an experiment template by name to its ID."""
        templates = self.templates.read_experiments_templates()
        for t in templates:
            if t.title == name:
                return t.id
        return None

    def _has_title(self, title: str) -> bool:
        """Check if an experiment title exists."""
        # Checks if title already exists
        return title in self.experiments_dict

    def _api_configuration(self):
        """Apply API settings from configuration to the OpenAPI client."""
        # Configures the API
        self.configuration = ep.Configuration()
        self.configuration.host = self.config["API_HOST_URL"]
        self.configuration.api_key["api_key"] = self.config["API_KEY"]
        self.configuration.api_key_prefix["api_key"] = "Authorization"
        self.configuration.verify_ssl = self.config["VERIFY_SSL"].lower() == "true"
        self.api_client = ep.ApiClient(self.configuration)
        self.api_client.set_default_header(
            header_name="Authorization",
            header_value=self.configuration.api_key["api_key"],
        )
        self.enforce_unique_titles = (
            self.config["UNIQUE_EXPERIMENTS_TITLES"].lower() == "true"
        )

    @staticmethod
    def _read_configuration_file(config_path: str) -> dict[str, str]:
        """Read key/value configuration file into a dictionary."""
        # Reads and parse configuration file, returns dictionnary
        config = {}
        with open(config_path) as f:
            for line in f:
                if line.strip() and not line.startswith("#"):
                    key, value = line.strip().split("=", 1)
                    config[key] = value
        return config
